import AppKit

/// Watches NSPasteboard.general for changes.
/// macOS has no equivalent of AddClipboardFormatListener, so we poll `changeCount` (cheap).
final class ClipboardMonitor {
    private let pb = NSPasteboard.general
    private var lastChangeCount: Int
    private var timer: Timer?
    private var skipChangeCount: Int?

    var settings: Settings
    /// Called on the main thread with the captured item.
    var onCapture: ((ClipItem) -> Void)?

    /// Pasteboard types that mark content as "don't record".
    /// See http://nspasteboard.org — honoured by 1Password, Bitwarden, Keychain etc.
    private static let concealedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
    ]

    /// Password managers whose copies are never recorded, regardless of user settings.
    /// Some of them (KeePassXC via Qt) don't manage to put org.nspasteboard.ConcealedType on the
    /// macOS pasteboard, so the bundle id is the only reliable signal.
    static let builtInIgnoredApps: Set<String> = [
        "org.keepassxc.keepassxc",
        "com.hicknhacksoftware.MacPass",
        "com.markmcguill.strongbox.mac",
        "net.antelle.keeweb",
        "com.1password.1password",
        "com.agilebits.onepassword7",
        "com.agilebits.onepassword-osx",
        "com.bitwarden.desktop",
        "com.lastpass.LastPass",
        "com.dashlane.Dashlane",
        "in.sinew.Enpass-Desktop",
        "com.keepersecurity.passwordmanager",
        "com.nordpass.mac",
        "com.roboform.RoboForm",
        "com.apple.keychainaccess",
        "com.apple.Passwords",
        "com.apple.PasswordsMenuBarExtra",
    ]

    init(settings: Settings) {
        self.settings = settings
        self.lastChangeCount = pb.changeCount
    }

    func start() {
        stop()
        let t = Timer(timeInterval: max(0.1, settings.pollInterval), repeats: true) { [weak self] _ in
            self?.tick()
        }
        // .common so polling keeps going while a menu is being tracked.
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    func updateSettings(_ s: Settings) {
        let restart = s.pollInterval != settings.pollInterval
        settings = s
        if restart, timer != nil { start() }
    }

    /// Perform a pasteboard write of our own without recording it as a new history entry.
    func performIgnoringChange(_ block: () -> Void) {
        block()
        skipChangeCount = pb.changeCount
        lastChangeCount = pb.changeCount
    }

    private func tick() {
        let cc = pb.changeCount
        guard cc != lastChangeCount else { return }
        lastChangeCount = cc

        if let skip = skipChangeCount, skip == cc {
            skipChangeCount = nil
            return
        }

        let frontApp = NSWorkspace.shared.frontmostApplication
        let bundleId = frontApp?.bundleIdentifier

        // Ignore list by bundle id: built-in password managers + the user's own list.
        if let id = bundleId, Self.builtInIgnoredApps.contains(id) || settings.ignoreApps.contains(id) { return }
        if let id = bundleId, id == Bundle.main.bundleIdentifier { return }

        if settings.ignoreConcealed, let types = pb.types {
            for t in types {
                let raw = t.rawValue
                if Self.concealedTypes.contains(raw) || raw.localizedCaseInsensitiveContains("concealed")
                    || raw.localizedCaseInsensitiveContains("password") { return }
            }
        }

        guard let item = ClipItem.capture(from: pb, settings: settings, sourceApp: bundleId) else { return }
        onCapture?(item)
    }
}
