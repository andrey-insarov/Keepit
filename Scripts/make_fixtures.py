#!/usr/bin/env python3
"""Reference .keepit files for Tests/KeepitTests/Fixtures/, written from docs/FORMAT.md alone.

This is an independent implementation of the format — Python, no Keepit code — so the Swift reader
is tested against something it did not write. Output is deterministic (fixed UUIDs, dates, salts,
nonces, PBKDF2 inputs) so re-running produces byte-identical files; the committed files are the
reference and are not regenerated by CI.

    pip install lzfse cryptography
    python3 Scripts/make_fixtures.py

Each fixture gets a sidecar <name>.json with the password and the expected outcome.
"""
import base64, hashlib, json, os, struct, uuid
import lzfse
from cryptography.hazmat.primitives import hashes
from cryptography.hazmat.primitives.ciphers.aead import AESGCM
from cryptography.hazmat.primitives.kdf.hkdf import HKDF

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "Tests", "KeepitTests", "Fixtures")
MAGIC = b"KEEPITBK"
ENC_MAGIC = b"KEEPITENC1"
V1_ROUNDS = 200_000

TEXT, RTF, HTML, PNG, FILES = ("public.utf8-plain-text", "public.rtf", "public.html", "public.png", "com.it.keep.file-list")

# A valid 1×1 red PNG.
PNG_1X1 = base64.b64decode(
    "iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mP8z8BQDwAEhQGAhKmMIQAAAABJRU5ErkJggg==")


def b64(b: bytes) -> str:
    return base64.b64encode(b).decode()


def sha256hex(b: bytes) -> str:
    return hashlib.sha256(b).hexdigest()


def fixed_uuid(n: int) -> str:
    return str(uuid.UUID(int=n))


def clip(n: int, formats: dict, source=None, date="2026-11-03T10:00:00Z"):
    """ClipItem per FORMAT.md; contentHash over the primary format."""
    primary = formats.get(FILES) or formats.get(TEXT) or formats.get(PNG) or next(iter(formats.values()))
    item = {
        "id": fixed_uuid(n),
        "date": date,
        "formats": {k: b64(v) for k, v in formats.items()},
        "contentHash": sha256hex(primary),
    }
    if source:
        item["sourceApp"] = source
    return item


def node(n: int, name: str, clip_=None, children=(), hot_key=None):
    d = {"id": fixed_uuid(n), "name": name, "children": list(children)}
    if clip_ is not None:
        d["clip"] = clip_
    if hot_key is not None:
        d["hotKey"] = hot_key
    return d


def root(children=()):
    return node(1000, "Template", children=children)


def payload(history, templates, settings=None, extra=None):
    p = {"version": 1, "created": "2026-11-03T10:12:45Z", "app": "make_fixtures.py (FORMAT.md v1)",
         "history": history, "templates": templates}
    if settings is not None:
        p["settings"] = settings
    if extra:
        p.update(extra)
    return p


def seal_v1(payload_obj, password: str, salt: bytes, nonce: bytes) -> bytes:
    js = json.dumps(payload_obj, sort_keys=True, separators=(",", ":"), ensure_ascii=False).encode()
    packed = lzfse.compress(js)
    key = hashlib.pbkdf2_hmac("sha256", password.encode(), salt, V1_ROUNDS, 32)
    ct = AESGCM(key).encrypt(nonce, packed, None)          # ciphertext || tag, no AAD in format 1
    return MAGIC + b"\x01" + salt + ENC_MAGIC + nonce + ct


# ---- format 2 (FORMAT.md) --------------------------------------------------------------------

def hkdf(ikm: bytes, salt: bytes, info: bytes) -> bytes:
    return HKDF(algorithm=hashes.SHA256(), length=32, salt=salt or None, info=info).derive(ikm)


def sealed_blob(plain: bytes, key: bytes, nonce: bytes) -> bytes:
    """vault.json / format-1 style blob: "KEEPITENC1" + nonce + ciphertext + tag, no AAD."""
    return ENC_MAGIC + nonce + AESGCM(key).encrypt(nonce, plain, None)


def header_bytes(h: dict) -> bytes:
    # Sorted keys, compact — but ANY serialisation is valid: the reader authenticates the bytes as found.
    return json.dumps(h, sort_keys=True, separators=(",", ":"), ensure_ascii=False).encode()


def seal_v2(payload_obj, header: dict, file_key: bytes, nonce: bytes, header_override: bytes = None) -> bytes:
    js = json.dumps(payload_obj, sort_keys=True, separators=(",", ":"), ensure_ascii=False).encode()
    packed = lzfse.compress(js)
    hb = header_override if header_override is not None else header_bytes(header)
    ct = AESGCM(file_key).encrypt(nonce, packed, hb)        # ciphertext || tag, AAD = header bytes
    return MAGIC + b"\x02" + struct.pack(">I", len(hb)) + hb + nonce + ct


def v2_header(mode, rounds, salt, recovery=None, **extra):
    h = {"mode": mode, "kdf": "pbkdf2-hmac-sha256", "rounds": rounds, "salt": b64(salt),
         "created": "2026-11-03T10:12:45Z", "app": "make_fixtures.py (FORMAT.md v2)", "minReader": "3.0"}
    if recovery:
        h["recovery"] = recovery
    h.update(extra)
    return h


def write(name: str, data: bytes, sidecar: dict):
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, name + ".keepit"), "wb") as f:
        f.write(data)
    with open(os.path.join(OUT, name + ".json"), "w", encoding="utf-8") as f:
        json.dump(sidecar, f, indent=2, ensure_ascii=False, sort_keys=True)
        f.write("\n")


def salt_for(name: str) -> bytes:
    return hashlib.sha256(b"salt:" + name.encode()).digest()[:16]


def nonce_for(name: str) -> bytes:
    return hashlib.sha256(b"nonce:" + name.encode()).digest()[:12]


def main():
    pw = "correct horse battery staple"
    fixtures = []

    # v1-empty
    fixtures.append(("v1-empty", payload([], root()), pw,
                     {"outcome": "ok", "history": 0, "templateNodes": 1, "settings": False}))

    # v1-text: plain, rich, with sourceApp
    rich = {TEXT: "Hello, world".encode(), RTF: rb"{\rtf1\ansi Hello, \b world\b0 }", HTML: b"<p>Hello, <b>world</b></p>"}
    fixtures.append(("v1-text", payload([
        clip(1, {TEXT: "first".encode()}),
        clip(2, rich),
        clip(3, {TEXT: "from Safari".encode()}, source="com.apple.Safari"),
    ], root()), pw, {
        "outcome": "ok", "history": 3,
        "texts": ["first", "Hello, world", "from Safari"],
        "kinds": ["text", "text", "text"],
        "sourceApps": [None, None, "com.apple.Safari"],
        "formatCounts": [1, 3, 1],
    }))

    # v1-image
    fixtures.append(("v1-image", payload([clip(4, {PNG: PNG_1X1})], root()), pw,
                     {"outcome": "ok", "history": 1, "kinds": ["image"], "pngBytes": [len(PNG_1X1)]}))

    # v1-files
    files = json.dumps(["/Users/alice/Documents/report.pdf", "/Users/alice/Pictures/cat.heic"]).encode()
    fixtures.append(("v1-files", payload([clip(5, {FILES: files})], root()), pw,
                     {"outcome": "ok", "history": 1, "kinds": ["files"],
                      "filePaths": [["/Users/alice/Documents/report.pdf", "/Users/alice/Pictures/cat.heic"]]}))

    # v1-templates: Work/Replies/Thanks, a separator, an item with an empty name, a hot key (⌥T: keyCode 17, optionKey 2048)
    tree = root([
        node(10, "Work", children=[
            node(11, "Replies", children=[
                node(12, "Thanks", clip(20, {TEXT: "Thanks!".encode()})),
            ]),
            node(13, "-", clip(21, {TEXT: "".encode()})),
            node(14, "", clip(22, {TEXT: "Untitled item".encode()})),
        ]),
        node(15, "Sig", clip(23, {TEXT: "-- Alice".encode()}), hot_key={"keyCode": 17, "modifiers": 2048}),
    ])
    fixtures.append(("v1-templates", payload([], tree), pw, {
        "outcome": "ok", "history": 0, "templateNodes": 7,
        "templatePaths": ["Work", "Work/Replies", "Work/Replies/Thanks", "Work/-", "Work/", "Sig"],
        "hotKeys": {"Sig": [17, 2048]},
    }))

    # v1-settings
    settings = {"historyMax": 123, "historyImageMax": 7, "menuMaxItems": 42, "launchAtLogin": False}
    fixtures.append(("v1-settings", payload([], root(), settings), pw,
                     {"outcome": "ok", "history": 0, "settings": True, "historyMax": 123, "historyImageMax": 7, "menuMaxItems": 42}))

    # v1-unknown-fields: extra keys at payload, item, node and settings level must be ignored
    item = clip(6, {TEXT: "known".encode()}); item["futureField"] = {"nested": [1, 2, 3]}
    tr = root([node(16, "Folder", children=[])]); tr["futureNodeField"] = "x"; tr["children"][0]["another"] = 1
    st = {"historyMax": 55, "futureSetting": True}
    fixtures.append(("v1-unknown-fields", payload([item], tr, st, extra={"futureTopLevel": "ignored"}), pw,
                     {"outcome": "ok", "history": 1, "texts": ["known"], "templateNodes": 2, "settings": True, "historyMax": 55}))

    for name, p, password, expect in fixtures:
        data = seal_v1(p, password, salt_for(name), nonce_for(name))
        # Independent per-format hashes of every history item, so the reader is checked on exact bytes.
        expect["formatHashes"] = [{uti: sha256hex(base64.b64decode(b)) for uti, b in item["formats"].items()} for item in p["history"]]
        write(name, data, {"format": 1, "password": password, **expect})

    # v1-wrong-password: same bytes as v1-text, sidecar says a different password
    data = seal_v1(payload([clip(1, {TEXT: "secret".encode()})], root()), pw, salt_for("v1-wrong-password"), nonce_for("v1-wrong-password"))
    write("v1-wrong-password", data, {"format": 1, "password": "not the password", "outcome": "wrongPassword"})

    # v1-truncated: a valid file cut in the middle of the ciphertext
    full = seal_v1(payload([clip(1, {TEXT: ("x" * 5000).encode()})], root()), pw, salt_for("v1-truncated"), nonce_for("v1-truncated"))
    write("v1-truncated", full[: len(full) * 2 // 3], {"format": 1, "password": pw, "outcome": "corruptOrWrongPassword"})

    # v1-bad-magic
    write("v1-bad-magic", b"KEEPITXX" + full[8:], {"format": None, "password": pw, "outcome": "notABackup"})

    # v1-future-format: format byte 9
    write("v1-future-format", MAGIC + b"\x09" + full[9:], {"format": 9, "password": pw, "outcome": "unsupportedVersion"})

    # ---- format 2 ----
    v2_payload = payload([clip(30, {TEXT: "v2 text".encode()}), clip(31, rich)], root([node(40, "Sig", clip(41, {TEXT: "-- Bob".encode()}))]))
    v2_expect = {"history": 2, "texts": ["v2 text", "Hello, world"], "templateNodes": 2,
                 "formatHashes": [{uti: sha256hex(base64.b64decode(b)) for uti, b in item["formats"].items()} for item in v2_payload["history"]]}

    # v2-manual: password for the file, 200 000 rounds
    name = "v2-manual"; salt = salt_for(name)
    key = hashlib.pbkdf2_hmac("sha256", pw.encode(), salt, 200_000, 32)
    write(name, seal_v2(v2_payload, v2_header("manual", 200_000, salt), key, nonce_for(name)),
          {"format": 2, "mode": "manual", "password": pw, "outcome": "ok", **v2_expect})

    # v2-auto: vault password + KDF params from "vault.json"; recovery block; label; ids
    name = "v2-auto"; salt = salt_for(name); vault_pw = "vault password 42"; rounds = 1_000
    data_key = hashlib.pbkdf2_hmac("sha256", vault_pw.encode(), salt, rounds, 32)
    entropy = hashlib.sha256(b"entropy:" + name.encode()).digest()          # 32 bytes = the 24-word phrase
    rsalt = hashlib.sha256(b"rsalt:" + name.encode()).digest()[:16]
    rkey = hkdf(entropy, rsalt, b"keepit-recovery-v1")
    recovery = {"salt": b64(rsalt),
                "wrappedKey": b64(sealed_blob(data_key, rkey, nonce_for(name + ":wk"))),
                "wrappedEntropy": b64(sealed_blob(entropy, data_key, nonce_for(name + ":we")))}
    file_key = hkdf(data_key, b"", b"keepit-backup-v2")
    hdr = v2_header("auto", rounds, salt, recovery, label="Fixture Mac", sourceID=fixed_uuid(500), backupID=fixed_uuid(501))
    auto_bytes = seal_v2(v2_payload, hdr, file_key, nonce_for(name))
    write(name, auto_bytes, {"format": 2, "mode": "auto", "password": vault_pw, "outcome": "ok",
                             "recoveryEntropyHex": entropy.hex(), "dataKeyHex": data_key.hex(), "label": "Fixture Mac", **v2_expect})

    # v2-auto-no-recovery: same, without a recovery block
    name = "v2-auto-no-recovery"
    write(name, seal_v2(v2_payload, v2_header("auto", rounds, salt), file_key, nonce_for(name)),
          {"format": 2, "mode": "auto", "password": vault_pw, "outcome": "ok", "dataKeyHex": data_key.hex(), **v2_expect})

    # v2-unknown-header-fields: extra header keys are ignored but authenticated
    name = "v2-unknown-header-fields"
    write(name, seal_v2(v2_payload, v2_header("manual", 200_000, salt_for("v2-manual"), futureHeaderField={"x": 1}), key, nonce_for(name)),
          {"format": 2, "mode": "manual", "password": pw, "outcome": "ok", **v2_expect})

    # v2-tampered-header: one character of the label changed after sealing → authentication fails
    name = "v2-tampered-header"
    hb = header_bytes(hdr)
    tampered = hb.replace(b"Fixture Mac", b"Fixture Mad")
    assert tampered != hb and len(tampered) == len(hb)
    body = auto_bytes[8 + 1 + 4 + len(hb):]
    write(name, MAGIC + b"\x02" + struct.pack(">I", len(tampered)) + tampered + body,
          {"format": 2, "mode": "auto", "password": vault_pw, "outcome": "wrongPassword"})

    # v2-minreader-future
    name = "v2-minreader-future"
    write(name, seal_v2(v2_payload, v2_header("manual", 200_000, salt_for("v2-manual"), minReader="99.0"), key, nonce_for(name)),
          {"format": 2, "password": pw, "outcome": "needsNewerKeepit", "minReader": "99.0"})

    # v2-rounds-out-of-range (10) and v2-unknown-kdf → rejected before any key derivation
    name = "v2-rounds-out-of-range"
    write(name, seal_v2(v2_payload, v2_header("manual", 10, salt_for("v2-manual")), key, nonce_for(name)),
          {"format": 2, "password": pw, "outcome": "corrupt"})
    name = "v2-unknown-kdf"
    h = v2_header("manual", 200_000, salt_for("v2-manual")); h["kdf"] = "argon2id"
    write(name, seal_v2(v2_payload, h, key, nonce_for(name)), {"format": 2, "password": pw, "outcome": "corrupt"})

    # v2-bad-header-length: length field claims more bytes than the file has
    name = "v2-bad-header-length"
    good = seal_v2(v2_payload, v2_header("manual", 200_000, salt_for("v2-manual")), key, nonce_for(name))
    write(name, good[:9] + struct.pack(">I", 10_000_000) + good[13:], {"format": 2, "password": pw, "outcome": "corrupt"})

    # v2-payload-future: container fine, payload.version = 999
    name = "v2-payload-future"
    fut = dict(v2_payload); fut["version"] = 999
    write(name, seal_v2(fut, v2_header("manual", 200_000, salt_for("v2-manual")), key, nonce_for(name)),
          {"format": 2, "password": pw, "outcome": "unsupportedPayloadVersion", "payloadVersion": 999})

    print("wrote", len(os.listdir(OUT)) // 2, "fixtures to", os.path.relpath(OUT))


if __name__ == "__main__":
    main()
